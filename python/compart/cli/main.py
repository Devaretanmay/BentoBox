def _resolve_real_binary(agent_name: str, workspace_root: str) -> str | None:
    """Resolve the real agent binary, excluding Compart's own shim dir from PATH."""
    shim_dir = os.path.abspath(os.path.join(workspace_root, ".compart", "bin"))
    clean_path = os.pathsep.join(
        p for p in os.environ.get("PATH", "").split(os.pathsep)
        if p and os.path.abspath(p) != shim_dir
    )
    return shutil.which(agent_name, path=clean_path)


def _write_shims(compart_dir: str) -> list[str]:
    """Detect installed agents and write shim scripts into .compart/bin/."""
    bin_dir = os.path.join(compart_dir, "bin")
    os.makedirs(bin_dir, exist_ok=True)
    created = []
    for agent in _KNOWN_AGENTS:
        real = shutil.which(agent)
        if not real:
            continue
        shim_path = os.path.join(bin_dir, agent)
        with open(shim_path, "w", encoding="utf-8") as f:
            f.write(_SHIM_TEMPLATE.format(agent=agent, real_path=real))
        os.chmod(shim_path, os.stat(shim_path).st_mode | stat.S_IEXEC | stat.S_IXGRP | stat.S_IXOTH)
        created.append(agent)
    return created


def cmd_init(args):
    """Initialize a Compart workspace in the current directory."""
    for sub in ("state", "logs", "snapshots", "sessions", "lanes", "executions", "integration"):
        os.makedirs(os.path.join(COMPART_DIR, sub), exist_ok=True)

    if not os.path.exists(CONFIG_FILE):
        with open(CONFIG_FILE, "w", encoding="utf-8") as f:
            f.write(_CONFIG_YAML_TEMPLATE)

    if not os.path.exists(TOPOLOGY_FILE):
        project_name = os.path.basename(os.path.abspath("."))
        _save_topology({"name": project_name, "compartments": {}, "connections": []})

    created_shims = _write_shims(COMPART_DIR)

    project_name = os.path.basename(os.path.abspath("."))
    print(f"Initialized Compart workspace in {os.path.abspath(COMPART_DIR)}/\n")

    detected = []
    if shutil.which("git"):
        detected.append("Git")
    detected += [_AGENT_DISPLAY.get(a, a.capitalize()) for a in created_shims]
    if detected:
        print(f"Detected: {', '.join(detected)}")
        for a in created_shims:
            real = shutil.which(a)
            print(f"  {a:<12} -> {real}")
        print()

    cfg = load_config(CONFIG_FILE)
    default_comp = cfg.compartments.get("default")
    fs_label = getattr(default_comp, "filesystem", "workspace") if default_comp else "workspace"
    net_label = getattr(default_comp, "network", "restricted") if default_comp else "restricted"
    print(f"Default policy: {fs_label} filesystem | {net_label} network | protected credentials\n")
    print("Commands:")
    print("  Run an agent:      compart claude | opencode | codex")
    print("  Create a workflow: compart -w <name>")
    print("  Add steps:         compart step <name> <file_or_dir>")
    print("  Run workflow:      compart run <name>")


def cmd_status(args):
    """Show workspace status: running executions, lanes, security events."""
    ws_root = find_workspace_root()
    if not ws_root:
        print("Error: Not inside a Compart workspace. Run 'compart init' first.")
        sys.exit(1)

    project_name = os.path.basename(ws_root)
    cfg = load_config(os.path.join(ws_root, ".compart", "config.yaml"))
    exec_mgr = ExecutionManager(workdir=ws_root)
    lane_mgr = LaneManager(workdir=ws_root)
    sess_mgr = SessionManager(workdir=ws_root)

    running = exec_mgr.list_running()
    all_execs = exec_mgr.list_all()
    lanes = lane_mgr.list_lanes()
    sessions = sess_mgr.list_sessions()

    blocked = sum(
        1 for ex in all_execs
        for ev in ex.events
        if "blocked" in ev.get("name", "").lower() or "denied" in ev.get("name", "").lower()
    )

    print(f"\nCOMPART WORKSPACE: {project_name}\n")

    if running:
        print("AGENTS RUNNING")
        for ex in running:
            dur = f"{ex.duration_s:.0f}s" if ex.duration_s else "?"
            changes = len(ex.changes)
            print(f"  * {ex.agent_name:<12} {ex.compartment_id:<12} pid:{ex.pid or '?':<8} {changes} change(s)  ({dur})")
    else:
        print("AGENTS RUNNING\n  none")

    print()
    completed = [s for s in sessions if s.status == SessionStatus.COMPLETED][:3]
    if completed:
        print("RECENT SESSIONS")
        for s in completed:
            dur = round(((s.finished_at or 0) - (s.started_at or 0)), 1)
            print(f"  [OK] {s.agent:<12} lane:{s.lane_id:<12} {len(s.changes)} change(s)  ({dur}s)")
    else:
        print("RECENT SESSIONS\n  none")

    print()
    workflows = [ex for ex in all_execs if ex.kind == ExecutionKind.WORKFLOW][:5]
    if workflows:
        print("WORKFLOWS")
        for wf in workflows:
            dur = f"{wf.duration_s:.0f}s" if wf.duration_s else "?"
            name = wf.command[1] if len(wf.command) > 1 else (wf.command[0] if wf.command else "?")
            print(f"  # {wf.execution_id:<12} {name:<24} {wf.status:<12} {len(wf.changes)} change(s)  ({dur})")
    else:
        print("WORKFLOWS\n  none")

    print()
    if lanes:
        print("LANES")
        for l in lanes:
            print(f"  {l.lane_id:<14} {l.agent_id:<12} {l.status:<12} {len(l.changes)} file(s)")
    else:
        print("LANES\n  none")

    print()
    print("SECURITY")
    print(f"  {blocked} blocked action(s)")
    print(f"  0 credential escapes")
    print()


def _snapshot_worktree(workspace_root: str, snapshot_id: str) -> str:
    """Copy the current worktree into ``.compart/snapshots/<snapshot_id>/``.

    Taken before a governed execution runs so its changes can later be
    undone / rolled back / restored.  Returns the snapshot directory.
    """
    snap_dir = os.path.join(workspace_root, ".compart", "snapshots", snapshot_id)
    SnapshotManager(workdir=workspace_root, snapshot_dir=snap_dir).snapshot()
    return snap_dir


def _resolve_compartment(
    cfg: WorkspaceConfig,
    agent_name: str,
    override: Optional[str] = None,
) -> CompartmentConfig:
    """Resolve the compartment for an execution.

    An explicit override always wins; otherwise the agent's configured default
    compartment applies; otherwise the workspace default.  Agent defaults are
    convenience routing, never security identity — every execution carries its
    own resolved policy.
    """
    if override:
        comp = cfg.compartments.get(override)
        if comp is None:
            print(
                f"Error: Unknown compartment '{override}'. "
                f"Declared: {sorted(cfg.compartments)}"
            )
            sys.exit(1)
        return comp
    return cfg.compartment_for_agent(agent_name)


def _launch_agent(
    agent_name: str,
    workspace_root: str,
    user_argv: Optional[List[str]] = None,
    compartment_name: Optional[str] = None,
) -> int:
    """Launch an interactive agent as a governed Execution.

    Creates an Execution + AgentSession, applies the resolved compartment
    policy in the PTY child before the real binary runs, and records the
    outcome.  Returns the child returncode (exits 127 if the binary is
    missing).
    """
    cfg = load_config(os.path.join(workspace_root, ".compart", "config.yaml"))
    compartment = _resolve_compartment(cfg, agent_name, compartment_name)
    policy = {"permissions": compartment.permissions}
    user_argv = list(user_argv or [])
    command = [agent_name] + user_argv

    real_binary = _resolve_real_binary(agent_name, workspace_root)
    if real_binary is None:
        print(f"Error: Could not find agent binary: {agent_name}")
        sys.exit(127)

    extra_env: dict[str, str] = {}
    agent_cfg = cfg.agents.get(agent_name)
    if agent_cfg:
        extra_env.update(agent_cfg.extra_env)
    if agent_name == "opencode":
        xdg_base = os.path.join(workspace_root, ".compart", "xdg")
        for sub in ("config", "data", "cache", "state"):
            os.makedirs(os.path.join(xdg_base, sub), exist_ok=True)
        extra_env.update({
            "XDG_CONFIG_HOME": os.path.join(xdg_base, "config"),
            "XDG_DATA_HOME": os.path.join(xdg_base, "data"),
            "XDG_CACHE_HOME": os.path.join(xdg_base, "cache"),
            "XDG_STATE_HOME": os.path.join(xdg_base, "state"),
        })

    exec_mgr = ExecutionManager(workdir=workspace_root)
    sess_mgr = SessionManager(workdir=workspace_root)

    execution = exec_mgr.create(
        kind=ExecutionKind.INTERACTIVE,
        command=command,
        compartment_id=compartment.name,
        policy=policy,
        extra_env=extra_env,
    )
    session = sess_mgr.create_session(
        agent_name=agent_name,
        task=" ".join(user_argv) if user_argv else f"Interactive {agent_name} session",
        compartment_name=compartment.name,
        permissions=policy.get("permissions", []),
    )
    execution.session_id = session.session_id

    before = index_workdir(workspace_root)
    execution.snapshot_dir = _snapshot_worktree(workspace_root, execution.execution_id)
    session.create_checkpoint("pre-execution", snapshot_manifest=execution.snapshot_dir)

    execution.start()
    exec_mgr.save(execution)
    session.start()
    sess_mgr.save_session(session)

    extra_env["COMPART_EXECUTION_ID"] = execution.execution_id

    supervisor = PtySupervisor(
        workdir=workspace_root,
        compartment_policy=policy,
        extra_env=extra_env,
    )

    stdin_is_tty = sys.stdin is not None and sys.stdin.isatty()
    if stdin_is_tty:
        returncode = supervisor.attach([real_binary] + user_argv)
    else:
        result = supervisor.capture([real_binary] + user_argv)
        if result.stdout:
            print(result.stdout, end="")
        returncode = result.returncode

    changes = diff_trees(before, index_workdir(workspace_root))
    execution.complete(returncode=returncode, changes=changes)
    exec_mgr.save(execution)
    session.complete(returncode=returncode, diffs=changes)
    sess_mgr.save_session(session)
    return returncode


def cmd_exec_shim(args):
    """Internal: called by workspace shim scripts to launch an agent under Compart.

    Usage: compart _exec_shim <agent_name> <workspace_root> [argv...]
    """
    if len(args.shim_args) < 2:
        print("Error: _exec_shim requires <agent_name> <workspace_root> [argv...]")
        sys.exit(1)

    agent_name = args.shim_args[0]
    workspace_root = args.shim_args[1]
    user_argv = args.shim_args[2:]
    returncode = _launch_agent(agent_name, workspace_root, user_argv=user_argv)
    sys.exit(returncode)


def cmd_inspect(args):
    """Dump declarative topology and state of the current project."""
    topology = _load_topology()
    if args.json:
        _print_json(topology)
    else:
        print(f"Compart Project: {topology.get('name', 'unnamed')}")
        comps = topology.get("compartments", {})
        conns = topology.get("connections", [])
        if not comps and not conns:
            print("Declared Topology: (empty)")
        else:
            print("Declared Topology:")
            print("  Compartments:")
            for name, cfg in comps.items():
                perms = cfg.get("permissions", [])
                print(f"    - {name} (permissions: {perms})")
            print("  Connections:")
            for edge in conns:
                if isinstance(edge, (list, tuple)) and len(edge) >= 2:
                    print(f"    - {edge[0]} -> {edge[1]}")


def cmd_compartment_create(args):
    """Define a new inner compartment in topology.json."""
    topology = _load_topology()
    comps = topology.setdefault("compartments", {})
    if args.name in comps:
        print(f"Error: Compartment '{args.name}' already declared.")
        sys.exit(1)
    comps[args.name] = {"permissions": ["fs_read"]}
    _save_topology(topology)
    print(f"Registered inner compartment '{args.name}'.")


def cmd_connect(args):
    """Establish a directional connection between two inner compartments."""
    topology = _load_topology()
    comps = topology.get("compartments", {})
    if args.source not in comps:
        print(f"Error: Source compartment '{args.source}' not declared.")
        sys.exit(1)
    if args.target not in comps:
        print(f"Error: Target compartment '{args.target}' not declared.")
        sys.exit(1)
    conns = topology.setdefault("connections", [])
    edge = [args.source, args.target]
    if edge not in conns:
        conns.append(edge)
    _save_topology(topology)
    print(f"Connected '{args.source}' -> '{args.target}'.")


def cmd_run(args):
    """Run a workflow or materialize declared topology."""
    target = getattr(args, "target", None)
    if target:
        class _WfArgs:
            workflow = target
            compartment = getattr(args, "compartment", "default") or "default"
            verbose = getattr(args, "verbose", False)
        cmd_workflow_run(_WfArgs())
        return

    ws_root = find_workspace_root() or os.path.abspath(".")
    cfg = load_config(os.path.join(ws_root, ".compart", "config.yaml"))
    if cfg.workflows:
        print("Available Workflows:")
        for wname in sorted(cfg.workflows):
            print(f"  - {wname:<24} (run with: compart run {wname})")
        return

    if os.path.exists(TOPOLOGY_FILE):
        topology = _load_topology()
        comps = topology.get("compartments", {})
        if comps:
            print(f"Materializing declared topology for '{topology.get('name', 'unnamed')}'...")
            compart = AgentCompart(workdir=ws_root, verbose=True)
            for name, cfg_comp in comps.items():
                perms = cfg_comp.get("permissions", ["fs_read"])
                def dummy_fn(ctx, n=name):
                    print(f"[{n}] Executing inside kernel sandbox...")
                    return {"status": "ok"}
                compart.add(Compartment(name=name, fn=dummy_fn, config=CompartmentConfig(permissions=perms)))
            for edge in topology.get("connections", []):
                if isinstance(edge, (list, tuple)) and len(edge) >= 2:
                    compart.edge(edge[0], edge[1])
            result = compart.run()
            if result.status == "error":
                print(f"\nExecution failed: {result.errors}")
                sys.exit(1)
            else:
                print("\nExecution succeeded.")
            return

    print("No workflow specified. Usage: compart run <workflow_name>")


def cmd_exec(args):
    """Run a command or launch an agent inside an explicitly selected compartment."""
    if not args.cmd:
        print("Error: No command provided to exec. Usage: compart exec [--compartment X] <command>")
        sys.exit(1)

    ws_root = find_workspace_root() or os.path.abspath(".")
    cfg = load_config(os.path.join(ws_root, ".compart", "config.yaml"))
    cmd = list(args.cmd)

    if cmd[0] in _KNOWN_AGENTS:
        returncode = _launch_agent(
            cmd[0], ws_root, user_argv=cmd[1:], compartment_name=args.compartment,
        )
        sys.exit(returncode)

    compartment = _resolve_compartment(cfg, cmd[0], args.compartment)
    policy = {"permissions": compartment.permissions}
    cmd_str = shlex.join(cmd)
    print(f"Executing: {cmd_str}  (compartment: {compartment.name})")

    runner = SandboxRunner(
        workdir=ws_root,
        verbose=True,
        block_network="network" not in compartment.permissions,
    )
    exec_mgr = ExecutionManager(workdir=ws_root)
    execution = exec_mgr.create(
        kind=ExecutionKind.PROCESS,
        command=cmd,
        compartment_id=compartment.name,
        policy=policy,
    )
    execution.snapshot_dir = _snapshot_worktree(ws_root, execution.execution_id)
    execution.start()
    exec_mgr.save(execution)

    result = runner.run(
        cmd_str,
        permissions=compartment.permissions,
        env={"COMPART_EXECUTION_ID": execution.execution_id},
    )
    if result.stdout:
        print(result.stdout)
    if result.stderr:
        print(result.stderr, file=sys.stderr)
    if result.error:
        print(f"\nSandbox error: {result.error}", file=sys.stderr)

    execution.complete(returncode=result.returncode, changes=result.diffs)
    exec_mgr.save(execution)

    if result.returncode != 0:
        print(f"\nExecution failed with code {result.returncode}")
        sys.exit(result.returncode)
    print("\nExecution succeeded.")


def cmd_wrap(args):
    """Transparently govern any CLI agent command in a managed AgentSession & Virtual Lane under kernel isolation."""
    ws_root = find_workspace_root() or os.path.abspath(".")
    agent_name = args.agent or "Claude Code"
    task = args.task
    cmd_str = ""
    env_vars = {}

    if args.claude is not None:
        agent_name = "Claude Code"
        raw_task = args.claude.strip()
        if raw_task.startswith("[") and raw_task.endswith("]"):
            raw_task = raw_task[1:-1].strip()
        task = raw_task or task or "Claude Code Execution Task"
        if not args.cmd:
            cmd_str = f"claude -p {shlex.quote(task)}"

    elif getattr(args, "opencode", None) is not None:
        agent_name = "OpenCode"
        raw_task = args.opencode.strip()
        if raw_task.startswith("[") and raw_task.endswith("]"):
            raw_task = raw_task[1:-1].strip()
        task = raw_task or task or "OpenCode Execution Task"
        xdg_base = os.path.join(ws_root, ".compart", "xdg")
        for sub in ["config", "data", "cache", "state"]:
            os.makedirs(os.path.join(xdg_base, sub), exist_ok=True)
        env_vars.update({
            "XDG_CONFIG_HOME": os.path.join(xdg_base, "config"),
            "XDG_DATA_HOME": os.path.join(xdg_base, "data"),
            "XDG_CACHE_HOME": os.path.join(xdg_base, "cache"),
            "XDG_STATE_HOME": os.path.join(xdg_base, "state"),
        })
        if not args.cmd:
            cmd_str = f"opencode run {shlex.quote(task)}" if task else "opencode --help"

    if not cmd_str and args.cmd:
        cmd_str = shlex.join(args.cmd)
        if not task:
            task = cmd_str

    if not cmd_str:
        print("Error: No command or task provided to wrap.")
        sys.exit(1)

    lane_id = getattr(args, "lane", "default") or "default"
    lane_mgr = LaneManager(workdir=ws_root)
    lane = lane_mgr.get_lane(lane_id)
    if not lane:
        lane = lane_mgr.create_lane(name=lane_id, agent_id=agent_name)

    session_mgr = SessionManager(workdir=ws_root)
    exec_mgr = ExecutionManager(workdir=ws_root)
    session = session_mgr.create_session(
        agent_name=agent_name,
        task=task,
        compartment_name=f"Compartment_{lane_id}",
        permissions=["fs_read", "fs_write", "fs_exec"],
        lane_id=lane_id,
    )

    kind = ExecutionKind.INTERACTIVE if agent_name in ("Claude Code", "OpenCode") else ExecutionKind.PROCESS
    execution = exec_mgr.create(
        kind=kind,
        command=shlex.split(cmd_str),
        compartment_id=f"Compartment_{lane_id}",
        policy={"permissions": ["fs_read", "fs_write", "fs_exec"]},
    )
    execution.session_id = session.session_id
    execution.snapshot_dir = _snapshot_worktree(ws_root, execution.execution_id)
    session.create_checkpoint("pre-execution", snapshot_manifest=execution.snapshot_dir)
    execution.start()
    exec_mgr.save(execution)
    session.start()
    session_mgr.save_session(session)

    lane.session_id = session.session_id
    lane.status = LaneStatus.ACTIVE
    lane_mgr.save_lane(lane)

    env_vars["COMPART_EXECUTION_ID"] = execution.execution_id

