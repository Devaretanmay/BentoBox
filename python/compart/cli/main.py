def _print_json(data: dict):
    print(json.dumps(data, indent=2))


def _load_topology() -> dict:
    if not os.path.exists(TOPOLOGY_FILE):
        print(f"Error: Not a compart project (missing {TOPOLOGY_FILE}). Run 'compart init' first.")
        sys.exit(1)
    with open(TOPOLOGY_FILE, "r", encoding="utf-8") as f:
        return json.load(f)


def _save_topology(topo: dict):
    with open(TOPOLOGY_FILE, "w", encoding="utf-8") as f:
        json.dump(topo, f, indent=2)
        f.write("\n")



_SHIM_TEMPLATE = """\
#!/usr/bin/env bash
# Compart workspace shim for: {agent}
# Auto-generated by `compart init`. Do NOT edit by hand.
set -e

_COMPART_REAL="{real_path}"

_find_workspace() {{
  local dir="$PWD"
  while [ "$dir" != "/" ]; do
    if [ -d "$dir/.compart" ]; then
      echo "$dir"
      return 0
    fi
    dir="$(dirname "$dir")"
  done
  return 1
}}

_ws="$(_find_workspace 2>/dev/null || true)"

if [ -n "$_ws" ]; then
  if [ -n "${{COMPART_EXECUTION_ID:-}}" ]; then
    # Already inside a Compart execution (an agent launched another agent).
    # Inherit the parent execution's kernel boundary — do not wrap again.
    exec "$_COMPART_REAL" "$@"
  fi
  # Delegate to the Compart exec shim, which applies the compartment policy
  # and records the execution as an AgentSession.
  exec python3 -m compart._exec_shim "{agent}" "$_ws" "$@"
else
  # Outside a workspace — run the real binary transparently.
  exec "$_COMPART_REAL" "$@"
fi
"""

